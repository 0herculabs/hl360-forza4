"""Finds functions that are only reachable through pointers stored in data.

Scans .rdata/.data of the dumped image (work/image/image.bin, see
`fm4tool image`) for words pointing into .text that
  - are not registered functions in generated/default/fm4_init.cpp,
  - are not branch targets (loc_ labels) in the generated code, and
  - follow a function end (blr, bctr, unconditional b, or padding).
Prints a [functions] TOML table for config/fptr_functions.toml. Review the
result: EH continuations inside a function also match (codegen then reports
unresolved branches around them).

Usage: python tools/find_fptrs.py > config/fptr_functions.toml
"""

import glob
import os
import re
import struct
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BASE = 0x82000000


def load_sections():
    sections = {}
    with open(os.path.join(ROOT, "work", "image", "sections.txt")) as f:
        for line in f:
            parts = line.split()
            if len(parts) == 4 and parts[0].startswith((".", "_", "B", "P")):
                sections[parts[0]] = (int(parts[1], 16), int(parts[1], 16) + int(parts[2], 16))
    return sections


def main():
    with open(os.path.join(ROOT, "work", "image", "image.bin"), "rb") as f:
        image = f.read()
    word = lambda a: struct.unpack_from(">I", image, a - BASE)[0]
    sections = load_sections()
    text = sections[".text"]

    gen = os.path.join(ROOT, "generated", "default")
    with open(os.path.join(gen, "fm4_init.cpp")) as f:
        funcs = {int(x, 16) for x in re.findall(r"\{ 0x([0-9A-F]{8}), ", f.read())}
    labels = set()
    for path in glob.glob(os.path.join(gen, "fm4_recomp.*.cpp")):
        with open(path) as f:
            labels.update(int(x, 16) for x in re.findall(r"\bloc_([0-9A-F]{8}):", f.read()))

    def candidate(v):
        if not (text[0] <= v < text[1]) or v % 4 or v in funcs or v in labels:
            return False
        if text[0] <= word(v) < text[1]:
            return False  # inline jump table entry, not code
        prev = word(v - 4)
        return prev in (0x4E800020, 0x4E800420, 0) or ((prev >> 26) == 18 and not prev & 1)

    found = set()
    # Pointers stored in data (vtables, callback tables).
    for name in (".rdata", ".data"):
        lo, hi = sections[name]
        for a in range(lo, hi - 3, 4):
            if candidate(word(a)):
                found.add(word(a))

    # Pointers materialized in code: lis rX,hi followed by addi/ori rY,rX,lo.
    lis = {}
    for a in range(text[0], text[1], 4):
        x = word(a)
        op, rd, ra, imm = x >> 26, (x >> 21) & 31, (x >> 16) & 31, x & 0xFFFF
        if x in (0x4E800020, 0x4E800420):
            lis.clear()
        elif op == 15 and ra == 0:  # lis
            lis[rd] = imm << 16
            continue
        elif op == 14 and ra in lis:  # addi
            v = (lis[ra] + (imm - 0x10000 if imm & 0x8000 else imm)) & 0xFFFFFFFF
            if candidate(v):
                found.add(v)
        elif op == 24 and rd in lis:  # ori rA,rS,imm (rS is bits 21-25)
            v = lis[rd] | imm
            if candidate(v):
                found.add(v)
        if op not in (14, 24) and rd in lis:
            lis.pop(rd)  # register overwritten (approximation)

    print("# Functions only reachable through pointers in .rdata/.data (vtables, callbacks).")
    print("# Generated by tools/find_fptrs.py; review before use.")
    print()
    print("[functions]")
    for v in sorted(found):
        print(f"0x{v:08X} = {{}}")
    print(f"{len(found)} candidates", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
